#!/usr/bin/env python3
"""Writes src/gen/: what links mupen64plus's core and plugins into one program.

mupen64plus loads its plugins with dlopen. RISC OS builds are static, and every plugin
exports the same names (PluginStartup, RomOpen, ...) and declares function pointers
named after the core's functions (ConfigOpenSection, ...). So each plugin is compiled
with -include prefix_<plugin>.h, which renames all those names to <plugin>_<name>, and
static_tables.c lists each library's exported functions by their real names, for
src/static_dynlib.c's osal_dynlib_getproc.

Run from the repository root after updating the vendored sources:
    python3 -I tools/gen_static.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
m64p = root / "mupen64plus"
out = root / "src" / "gen"

# name in the program -> (source folder, plugin type, file name ui-console sees)
PLUGINS = {
    "rice":   ("video-rice", "M64PLUGIN_GFX",   "mupen64plus-video-rice"),
    "rsphle": ("rsp-hle",    "M64PLUGIN_RSP",   "mupen64plus-rsp-hle"),
    "audsdl": ("audio-sdl",  "M64PLUGIN_AUDIO", "mupen64plus-audio-sdl"),
    "inpsdl": ("input-sdl",  "M64PLUGIN_INPUT", "mupen64plus-input-sdl"),
}

# compiled with a prefix too, but exporting nothing: ui-console's function pointers are
# named after the core's functions
PREFIX_ONLY = {"ui": "ui-console"}

# other global names that more than one library defines (found with nm on the Mac
# build); renamed in every prefixed library, harmless where unused
EXTRA = ["DebugMessage", "combinepath", "osal_mkdirp", "osal_is_directory",
         "osal_search_dir_open", "osal_search_dir_read_next", "osal_search_dir_close",
         "sdl_keysym2scancode", "sdl_scancode2keysym"]

EXPORT_DEF = re.compile(r"^\s*EXPORT\s[^;{]*?\bCALL\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", re.M)


def api_names():
    """Every function name in the API headers (ptr_<name> typedefs): core and plugin."""
    names = set()
    for h in (m64p / "core" / "src" / "api").glob("m64p_*.h"):
        names |= set(re.findall(r"\(\s*\*\s*ptr_([A-Za-z_][A-Za-z0-9_]*)\s*\)", h.read_text()))
    return sorted(names)


def exported(folder, globs=("*.c", "*.cpp")):
    names = set()
    for g in globs:
        for f in (m64p / folder).rglob(g):
            names |= set(EXPORT_DEF.findall(f.read_text(errors="replace")))
    return sorted(names)


def main():
    out.mkdir(parents=True, exist_ok=True)
    names = api_names()
    prefixed = {p: v[0] for p, v in PLUGINS.items()} | PREFIX_ONLY
    for p, folder in prefixed.items():
        lines = [f"/* Generated by tools/gen_static.py: {folder} linked into one program. */",
                 f"#ifndef PREFIX_{p.upper()}_H", f"#define PREFIX_{p.upper()}_H"]
        lines += [f"#define {n} {p}_{n}" for n in names + EXTRA]
        lines += ["#endif", ""]
        (out / f"prefix_{p}.h").write_text("\n".join(lines))

    core = exported("core/src/api", ("*.c",))
    c = ["/* Generated by tools/gen_static.py: each library's exported functions. */",
         '#include "static_dynlib.h"', ""]
    c.append("/* the core */")
    c += [f"extern void {n}(void);" for n in core]
    c.append("const struct static_symbol static_core_symbols[] = {")
    c += [f'    {{ "{n}", (void *) {n} }},' for n in core]
    c += ["    { 0, 0 }", "};", ""]
    for p, (folder, _, _) in PLUGINS.items():
        ex = exported(folder + "/src")
        c.append(f"/* {folder} */")
        c += [f"extern void {p}_{n}(void);" for n in ex]
        c.append(f"static const struct static_symbol {p}_symbols[] = {{")
        c += [f'    {{ "{n}", (void *) {p}_{n} }},' for n in ex]
        c += ["    { 0, 0 }", "};", ""]
    c.append("const struct static_library static_plugins[] = {")
    for p, (folder, ptype, fname) in PLUGINS.items():
        c.append(f'    {{ "{fname}", {ptype}, {p}_symbols }},')
    c += ["    { 0, 0, 0 }", "};", ""]
    (out / "static_tables.c").write_text("\n".join(c))
    print(f"{len(names)} API names; core exports {len(core)}; wrote {out}")


if __name__ == "__main__":
    main()
